node1 = fea.ChNodeFEbase()
node1.SetPos(chrono.ChVectorD(0, 0, 0))
node1.SetFixed(True)
system.Add(node1)

node2 = fea.ChNodeFEbase()
node2.SetPos(chrono.ChVectorD(beam_length, 0, 0))
system.Add(node2)


beam.AddNode(node1, True, True)
beam.AddNode(node2, False, False)
system.Add(beam)


