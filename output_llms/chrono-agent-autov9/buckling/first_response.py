"""Beam buckling simulation (PyChrono 9.0.1, FEA + Irrlicht).

Models the Euler buckling of a slender vertical column built from Euler-Bernoulli
FEA beam elements (`ChMesh` + `ChBuilderBeamEuler`). The column is clamped at its
base and loaded in axial compression at its free top end. The compressive load is
generated by a CUSTOM motor function (a `ChFunction` subclass) whose value ramps
linearly in time; that force is applied to the tip node along -Z via a
`ChLoadNodeXYZRotForceAbs` load whose base force is updated each step from the
custom function.

A rigid support assembly anchors the structure: a fixed `ground` body and a rigid
`support_base` body are joined by a 6-DOF `ChLinkMateGeneric` constraint (a
constraint between two distinct parts of the system, representing the bolted
foundation), and the column's base FEA node is clamped to that foundation.

As the applied load crosses the column's critical Euler load
(P_cr = pi^2 * E * I / (2L)^2 for a clamped-free column ~ 3.9 kN here), the
initially near-straight (but slightly imperfect) column loses lateral stability
and bows out sharply — the hallmark of buckling. The lateral tip deflection stays
small while the load is sub-critical and grows rapidly once it goes super-critical.

System type: ChSystemSMC (required for FEA), MKL Pardiso direct solver, and an HHT
timestepper for stiff implicit integration. The deforming column is visualized in
Irrlicht via a ChVisualShapeFEA; tip lateral and axial displacement plus the
applied load are logged to CSV and plotted.
"""

# === Imports ===
import os
import csv
import math

import numpy as np
import matplotlib
matplotlib.use("Agg")  # headless plotting backend (no display needed for the PNG)
import matplotlib.pyplot as plt

import pychrono.core as chrono
import pychrono.fea as fea
import pychrono.pardisomkl as mkl
import pychrono.irrlicht as chronoirr

# === Named constants (geometry / physics) ===
TIME_STEP = 5.0e-4          # FEA-stable implicit step
SIM_END = 3.8               # seconds of simulated time (load ramps past P_cr)
RENDER_FPS = 50.0           # review-video frame cadence

COLUMN_HEIGHT = 1.0         # m, length of the slender column (along +Z)
N_ELEMENTS = 16             # number of beam finite elements
SECTION_DIAM = 0.020        # m, circular cross-section diameter (slender)
DENSITY = 7800.0            # kg/m^3, steel
YOUNG_MOD = 2.0e11          # Pa, steel Young's modulus
SHEAR_MOD = YOUNG_MOD * 0.35
RAYLEIGH = 0.01             # cross-section Rayleigh damping

LATERAL_IMPERFECTION = 3.0e-3   # m, small initial tip offset to seed the buckling mode

# Compressive load ramp: f(t) = FORCE_RAMP_RATE * t (Newtons). The clamped-free
# Euler critical load is P_cr = pi^2*E*I/(2L)^2; with the values above P_cr ~ 3.9 kN,
# so the ramp crosses it partway through the run and buckling develops.
FORCE_RAMP_RATE = 2.0e3     # N per second of applied compressive force

SUPPORT_SIZE = chrono.ChVector3d(0.20, 0.20, 0.04)  # full extents of the rigid base plate

# Base of the column sits at this Z; it grows upward to COLUMN_HEIGHT.
COLUMN_BASE_Z = 0.0
COLUMN_TOP_Z = COLUMN_BASE_Z + COLUMN_HEIGHT


# === Custom motor function: linearly ramped compressive load ===
class RampForceFunction(chrono.ChFunction):
    """Custom ChFunction returning a load magnitude that grows linearly with time.

    f(t) = rate * t  (Newtons, magnitude). Sampled each step to set the tip's
    compressive force base along -Z, so the column is squeezed harder over time.
    """

    def __init__(self, rate):
        super().__init__()
        self.rate = rate  # cache: ramp slope, set once at construction

    def GetVal(self, t):
        return self.rate * t

    def Clone(self):
        return RampForceFunction(self.rate)


def main():
    # === System & gravity ===  build the SMC system FEA requires
    sys = chrono.ChSystemSMC()
    sys.SetGravitationalAcceleration(chrono.ChVector3d(0, 0, -9.81))
    sys.SetCollisionSystemType(chrono.ChCollisionSystem.Type_BULLET)

    # === Solver & timestepper ===  MKL direct solver + HHT for stiff FEA dynamics
    sys.SetSolver(mkl.ChSolverPardisoMKL())
    # NOTE (this 9.0.1 build): SetTimestepper(obj) has a broken shared_ptr binding
    # and the live HHT stepper exposes no tuning setter, so we select HHT by TYPE
    # and rely on its robust default damping. The type is what matters for stiff FEA.
    sys.SetTimestepperType(chrono.ChTimestepper.Type_HHT)
    stepper = sys.GetTimestepper()  # cache: live stepper handle, fetched once
    assert stepper.GetType() == chrono.ChTimestepper.Type_HHT, "HHT not active"

    # === Ground & support constraint ===  rigid foundation = two parts + a 6-DOF mate
    ground = chrono.ChBody()
    ground.SetFixed(True)
    ground.SetName("ground")
    sys.Add(ground)

    support_base = chrono.ChBody()
    support_base.SetMass(2.0)
    support_base.SetPos(chrono.ChVector3d(0, 0, COLUMN_BASE_Z - 0.5 * SUPPORT_SIZE.z))
    support_base.SetName("support_base")
    support_vis = chrono.ChVisualShapeBox(SUPPORT_SIZE.x, SUPPORT_SIZE.y, SUPPORT_SIZE.z)
    support_vis.SetColor(chrono.ChColor(0.3, 0.3, 0.35))
    support_base.AddVisualShape(support_vis)
    sys.Add(support_base)

    # Constraint between two distinct parts: bolt the support plate to the ground
    # (all 6 DOF locked). A rigid-rigid mate is well-conditioned for HHT.
    foundation = chrono.ChLinkMateGeneric()
    foundation.Initialize(
        support_base, ground, False,
        chrono.ChFramed(support_base.GetPos(), chrono.QUNIT),
        chrono.ChFramed(support_base.GetPos(), chrono.QUNIT),
    )
    foundation.SetConstrainedCoords(True, True, True, True, True, True)
    foundation.SetName("foundation_bolt")
    sys.Add(foundation)

    # === FEA mesh & beam section ===  slender circular steel column
    mesh = fea.ChMesh()
    mesh.SetAutomaticGravity(True)

    sec = fea.ChBeamSectionEulerAdvanced()
    sec.SetAsCircularSection(SECTION_DIAM)
    sec.SetDensity(DENSITY)
    sec.SetYoungModulus(YOUNG_MOD)
    sec.SetShearModulus(SHEAR_MOD)
    sec.SetRayleighDamping(RAYLEIGH)

    # FEA beam: no contact material needed — driven by constraints + gravity + load only.

    # Build the vertical beam. A tiny lateral X-offset at the top seeds the buckling
    # mode so the column bows in a deterministic direction instead of staying
    # perfectly (and unstably) straight.
    up_ref = chrono.ChVector3d(1, 0, 0)  # cross-section lateral reference direction
    builder = fea.ChBuilderBeamEuler()
    builder.BuildBeam(
        mesh, sec, N_ELEMENTS,
        chrono.ChVector3d(0.0, 0.0, COLUMN_BASE_Z),
        chrono.ChVector3d(LATERAL_IMPERFECTION, 0.0, COLUMN_TOP_Z),
        up_ref,
    )

    # SWIG GC guard: keep a strong reference to the node container before indexing.
    beam_nodes = builder.GetLastBeamNodes()
    base_node = beam_nodes.front()
    tip_node = beam_nodes.back()

    # Clamp the base node — this fully fixes the column root to the foundation.
    base_node.SetFixed(True)

    sys.Add(mesh)

    # === Compressive load with custom function ===  axial -Z force on the tip node
    load_container = chrono.ChLoadContainer()
    sys.Add(load_container)
    tip_load = fea.ChLoadNodeXYZRotForceAbs(tip_node, chrono.ChVector3d(0, 0, 0))
    load_container.Add(tip_load)
    ramp_fun = RampForceFunction(FORCE_RAMP_RATE)  # cache: custom motor function, built once

    # === FEA visualization shape ===  color the column by node speed; wire overlay
    vis_beam = chrono.ChVisualShapeFEA()
    vis_beam.SetFEMdataType(chrono.ChVisualShapeFEA.DataType_NODE_SPEED_NORM)
    vis_beam.SetColormapRange(chrono.ChVector2d(0.0, 0.5))
    vis_beam.SetSmoothFaces(True)
    mesh.AddVisualShapeFEA(vis_beam)

    vis_wire = chrono.ChVisualShapeFEA()
    vis_wire.SetFEMdataType(chrono.ChVisualShapeFEA.DataType_SURFACE)
    vis_wire.SetWireframe(True)
    vis_wire.SetDrawInUndeformedReference(True)
    mesh.AddVisualShapeFEA(vis_wire)

    # === Precomputed loop constants ===  computed ONCE before the loop
    render_every = max(1, round(1.0 / (RENDER_FPS * TIME_STEP)))  # precomputed once
    headless = bool(os.environ.get("SIMBENCH_VALIDATE"))  # fast windowless validation run
    run_end = min(SIM_END, 0.5) if headless else SIM_END   # short physics check when validating
    tip0 = tip_node.GetPos()  # cache: undeformed tip position, reused every step

    # === Visualization === full Irrlicht scene: window + sky + camera + lights + grid
    vis = None
    if not headless:
        vis = chronoirr.ChVisualSystemIrrlicht()
        vis.AttachSystem(sys)
        vis.SetCameraVertical(chrono.CameraVerticalDir_Z)  # gravity along -Z
        vis.SetWindowSize(1280, 720)
        vis.SetWindowTitle("Beam Buckling (FEA + Irrlicht)")
        vis.Initialize()  # Initialize FIRST, then add scene elements
        vis.AddLogo(chrono.GetChronoDataFile("logo_pychrono_alpha.png"))
        vis.AddSkyBox()
        vis.AddCamera(chrono.ChVector3d(1.8, -2.0, 1.1),
                      chrono.ChVector3d(0.0, 0.0, COLUMN_HEIGHT * 0.5))
        vis.AddTypicalLights()
        vis.AddGrid(0.1, 0.1, 30, 30,
                    chrono.ChCoordsysd(chrono.ChVector3d(0, 0, 0), chrono.QUNIT),
                    chrono.ChColor(0.4, 0.4, 0.4))

    # === Main loop ===  render-cadence outer loop; physics + CSV logging inner batch
    os.makedirs("frames", exist_ok=True)  # guard against missing output dir

    times, lateral_def, axial_def, applied_force = [], [], [], []
    csv_file = None
    try:
        try:
            csv_file = open("simulation_data.csv", "w", newline="")  # noqa: SIM115
        except (OSError, IOError) as exc:  # disk full / permission denied
            print(f"Could not open CSV for writing: {exc}")
            raise
        writer = csv.writer(csv_file)
        writer.writerow([
            "time_s", "tip_x_m", "tip_z_m",
            "lateral_deflection_m", "axial_shortening_m", "applied_force_N",
        ])

        frame = 0
        while (headless or vis.Run()) and sys.GetChTime() < run_end:
            if not headless:
                vis.BeginScene()
                vis.Render()
                vis.EndScene()
                vis.WriteImageToFile(f"frames/img_{frame:06d}.png")  # consecutive index -> ffmpeg
                frame += 1

            for _ in range(render_every):
                t = sys.GetChTime()
                # Sample the custom function and push the compressive load (-Z).
                fval = ramp_fun.GetVal(t)
                tip_load.SetForceBase(chrono.ChVector3d(0.0, 0.0, -fval))

                pos = tip_node.GetPos()
                lat = math.sqrt(pos.x * pos.x + pos.y * pos.y)  # radial lateral offset
                axial = tip0.z - pos.z  # downward shortening of the column top

                times.append(t)
                lateral_def.append(lat)
                axial_def.append(axial)
                applied_force.append(fval)
                writer.writerow([f"{t:.6f}", f"{pos.x:.8f}", f"{pos.z:.8f}",
                                 f"{lat:.8f}", f"{axial:.8f}", f"{fval:.4f}"])

                sys.DoStepDynamics(TIME_STEP)
                if sys.GetChTime() >= run_end:
                    break
    except (RuntimeError, ValueError) as exc:  # solver divergence / bad numeric state
        import traceback
        traceback.print_exc()
        print(f"Simulation aborted: {exc}")
        raise
    finally:
        if csv_file is not None:
            csv_file.close()  # flush partial CSV even if a step diverged

    # === Post-processing ===  plot logged time series to PNG
    if times:
        fig, ax1 = plt.subplots(figsize=(9, 5))
        ax1.plot(times, lateral_def, color="tab:red", label="lateral deflection (m)")
        ax1.plot(times, axial_def, color="tab:blue", label="axial shortening (m)")
        ax1.set_xlabel("time (s)")
        ax1.set_ylabel("tip displacement (m)")
        ax1.grid(True)
        ax2 = ax1.twinx()
        ax2.plot(times, applied_force, color="tab:green",
                 linestyle="--", label="applied force (N)")
        ax2.set_ylabel("applied compressive force (N)")
        lines1, labels1 = ax1.get_legend_handles_labels()
        lines2, labels2 = ax2.get_legend_handles_labels()
        ax1.legend(lines1 + lines2, labels1 + labels2, loc="upper left")
        plt.title("Beam buckling: tip deflection vs. ramped compressive load")
        fig.tight_layout()
        fig.savefig("simulation_timeseries.png", dpi=120)
        plt.close(fig)

    max_lat = max(lateral_def) if lateral_def else 0.0
    max_ax = max(axial_def) if axial_def else 0.0
    print(f"Done. steps logged={len(times)}, "
          f"max lateral deflection={max_lat:.4f} m, max axial shortening={max_ax:.4f} m")


if __name__ == "__main__":
    main()
