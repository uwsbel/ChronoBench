def load_obj_mesh(path):
    with open(path, "r") as file:
        lines = file.readlines()
    vertices = []
    faces = []
    for line in lines:
        if line.startswith("v "):
            vertices.append(list(map(float, line.strip().split()[1:])))
        elif line.startswith("f "):
            face = [int(part.split("/")[0]) - 1 for part in line.strip().split()[1:]]
            faces.append(face)
    return vertices, faces


def create_visual_box(system, name, pos, size, color):
    box = chrono.ChVisualShapeBox(size[0], size[1], size[2])
    box.SetColor(chrono.ChColor(color[0], color[1], color[2]))
    body = chrono.ChBodyEasyBox(size[0], size[1], size[2], 1000, True, True)
    body.SetName(name)
    body.SetPos(pos)
    body.SetFixed(True)
    body.AddVisualShape(box)
    system.AddBody(body)
    return body


