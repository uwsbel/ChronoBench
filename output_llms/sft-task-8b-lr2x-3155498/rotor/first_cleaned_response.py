import pychrono as chrono
import numpy as np


system = chrono.ChSystemNSC()
system.SetGravitationalAcceleration(chrono.ChVector3d(0, 0, 0))
visualizer = chrono.ChVisualSystemIrrlicht()
visualizer.AttachSystem(system)
visualizer.SetWindowSize(1024, 768)
visualizer.SetWindowTitle("Jeffcott Rotor with IGA Beam")
visualizer.Initialize()
visualizer.AddSkyBox()
visualizer.AddCamera(chrono.ChVector3d(0, 2.5, 3), chrono.ChVector3d(0, 0, 0))
visualizer.AddTypicalLights()


def create_iga_beam(length, thickness, material):
    beam = chrono.ChLineIGA()
    beam.SetUseNormalizedCoordinates(True)
    beam.SetUseCurvature(True)
    beam.SetNdiv(20)
    beam.SetThickness(thickness)
    beam.SetMaterialSurface(material)
    return beam


def add_flywheel(body, radius, mass, position):
    flywheel = chrono.ChBodyEasySphere(radius, 1000, True, True)
    flywheel.SetMass(mass)
    flywheel.SetInertiaXX(chrono.ChVector3d(mass * radius**2 / 2, mass * radius**2 / 2, mass * radius**2 / 2))
    flywheel.SetPos(position)
    flywheel.SetName("Jeffcott flywheel")
    flywheel.GetVisualShape(0).SetColor(chrono.ChColor(0.8, 0.1, 0.1))
    body.Add(flywheel)
    return flywheel


def add_rotational_motor(body_a, body_b, axis):
    motor = chrono.ChLinkMotorRotationSpeed()
    motor.Initialize(body_a, body_b, chrono.ChFramed(chrono.ChVector3d(0, 0, 0), chrono.QUNIT))
    motor.SetSpeedFunction(chrono.ChFunctionConst(0.0))
    return motor


def add_ground_visual():
    ground = chrono.ChBodyEasyBox(10, 0.1, 10, 1000, True, False)
    ground.SetFixed(True)
    ground.SetName("Jeffcott rotor ground")
    ground.GetVisualShape(0).SetColor(chrono.ChColor(0.4, 0.4, 0.4))
    ground.GetVisualShape(0).SetOpacity(0.3)
    system.AddBody(ground)
    return ground


def add_beam_visual(beam):
    visual = chrono.ChVisualShapeLine()
    visual.SetColor(chrono.ChColor(0.1, 0.4, 0.8))
    beam.AddVisualShape(visual)
    return visual


def add_flywheel_visual(flywheel):
    flywheel.GetVisualShape(0).SetColor(chrono.ChColor(0.8, 0.1, 0.1))
    flywheel.GetVisualShape(0).SetRadius(0.12)


def add_motor_visual(motor):
    shaft = chrono.ChVisualShapeCylinder(0.025, 0.15)
    shaft.SetColor(chrono.ChColor(0.2, 0.2, 0.2))
    motor.AddVisualShape(shaft)


def add_axis_visual(axis):
    axis_shape = chrono.ChVisualShapeCylinder(0.015, 0.1)
    axis_shape.SetColor(chrono.ChColor(0.1, 0.1, 0.1))
    return axis_shape


