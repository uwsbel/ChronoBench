import pychrono as chrono 
import pychrono.fea as fea 
import pychrono.pardisomkl as mkl 
import pychrono.irrlicht as chronoirr 

print("Example: PyChrono using beam finite elements") 


sys = chrono.ChSystemSMC()


mesh = fea.ChMesh()


msection = fea.ChBeamSectionEulerAdvanced()


beam_wy = 0.012
beam_wz = 0.025
msection.SetAsRectangularSection(beam_wy, beam_wz) 


msection.SetYoungModulus(0.01e9) 
msection.SetShearModulus(0.01e9 * 0.3) 
msection.SetRayleighDamping(0.000) 
msection.SetCentroid(0, 0.02) 
msection.SetShearCenter(0, 0.1) 
msection.SetSectionRotation(45 * chrono.CH_RAD_TO_DEG) 


beam_L = 0.1


hnode1 = fea.ChNodeFEAxyzrot(chrono.ChFramed(chrono.ChVector3d(0, 0, -0.1))) 
hnode2 = fea.ChNodeFEAxyzrot(chrono.ChFramed(chrono.ChVector3d(beam_L, 0, -0.1))) 
hnode3 = fea.ChNodeFEAxyzrot(chrono.ChFramed(chrono.ChVector3d(beam_L * 2, 0, -0.1))) 
hnode4 = fea.ChNodeFEAxyzrot(chrono.ChFramed(chrono.ChVector3d(beam_L * 3, 0, -0.1))) 


mesh.AddNode(hnode1)
mesh.AddNode(hnode2)
mesh.AddNode(hnode3)
mesh.AddNode(hnode4)


builder = fea.ChBuilderBeamEuler()
builder.BuildBeam(hnode1, hnode2, msection, 5)
beelement1 = builder.GetBeamElements()[0]
beelement1.SetNodes(hnode1, hnode2) 
mesh.AddElement(beelement1) 


builder.BuildBeam(hnode2, hnode3, msection, 5)
beelement2 = builder.GetBeamElements()[1]
beelement2.SetNodes(hnode2, hnode3) 
mesh.AddElement(beelement2) 


constr_bc = chrono.ChLinkMateGeneric()
constr_bc.Initialize(hnode2, chrono.ChBody(), False, hnode2.Frame(), hnode2.Frame())
constr_bc.SetConstrainedCoords(True, True, True, 
                                True, True, True) 
sys.Add(constr_bc) 


hnode2.SetForce(chrono.ChVector3d(4, 2, 0))


hnode3.SetTorque(chrono.ChVector3d(0, -0.04, 0))


mtruss = chrono.ChBody()
mtruss.SetFixed(True) 
sys.Add(mtruss) 


constr_bc = chrono.ChLinkMateGeneric()
constr_bc.Initialize(hnode3, mtruss, False, hnode3.Frame(), hnode3.Frame())
sys.Add(constr_bc) 


























