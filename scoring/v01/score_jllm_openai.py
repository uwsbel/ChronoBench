def call_judge(client: object, args: argparse.Namespace, prompt: str) -> str:
    last_error = None
    for attempt in range(1, args.retries + 1):
        try:
            completion = client.chat.completions.create(
                model=args.judge_model,
                messages=[{"role": "user", "content": prompt}],
                temperature=args.temperature,
                top_p=args.top_p,
                max_tokens=args.max_tokens,
                stream=False,
            )
            return completion.choices[0].message.content or ""
        except Exception as exc:
            last_error = exc
            if attempt < args.retries:
                time.sleep(args.retry_sleep)
    raise RuntimeError(f"Judge call failed after {args.retries} retries: {last_error}")


def extract_score(text: str) -> float:
    match = re.search(r"\[\[\s*(\d+(?:\.\d+)?)\s*\]\]", text)
    if not match:
        raise ValueError("No score in [[x]] format found")
    return float(match.group(1))


def maybe_extract_score(path: Path) -> float | str:
    if not path.exists() or path.stat().st_size == 0:
        return ""
    try:
        return extract_score(read_text(path))
    except ValueError:
        return "ERROR: No valid scores from judges"


def valid_count(system_dir: Path, round_name: str, mode: str) -> int | str:
    path = system_dir / f"{round_name}_evaluation_{mode}.json"
    if not path.exists() or path.stat().st_size == 0:
        return ""
    try:
        data = json.loads(read_text(path))
    except json.JSONDecodeError:
        return ""
    return data.get("valid_count", "")


def write_system_csv(system_dir: Path, model_name: str, system_name: str) -> None:
    rows = [
        [
            "Test Model",
            "System",
            "Round",
            "Score Document",
            "Score Reference",
            "Score Reference Document",
            "Document Judge Count",
            "Reference Judge Count",
            "Reference Document Judge Count",
        ]
    ]
    for round_name in ROUND_NAMES:
        rows.append(
            [
                model_name,
                system_name,
                round_name,
                maybe_extract_score(score_path(system_dir, round_name, "document")),
                maybe_extract_score(score_path(system_dir, round_name, "reference")),
                maybe_extract_score(score_path(system_dir, round_name, "reference_document")),
                valid_count(system_dir, round_name, "document"),
                valid_count(system_dir, round_name, "reference"),
                valid_count(system_dir, round_name, "reference_document"),
            ]
        )

    with (system_dir / "evaluation_scores.csv").open("w", newline="", encoding="utf-8") as csvfile:
        writer = csv.writer(csvfile)
        writer.writerows(rows)


def run_judges(client: object, args: argparse.Namespace, prompt: str) -> tuple[str, list[dict], list[float]]:
    attempts = []
    valid_scores = []
    for judge_idx in range(1, args.judge_repeats + 1):
        response = ""
        error = ""
        score = None
        try:
            response = call_judge(client, args, prompt)
            score = extract_score(response)
            valid_scores.append(score)
        except Exception as exc:
            error = str(exc)
        attempts.append(
            {
                "judge_index": judge_idx,
                "score": score,
                "error": error,
                "response": response,
            }
        )

    if valid_scores:
        average_score = sum(valid_scores) / len(valid_scores)
        parts = [
            f"Valid scores: {valid_scores}",
            f"Valid count: {len(valid_scores)}",
            f"Average score: {average_score:.6f}",
            f"[[{average_score:.6f}]]",
        ]
    else:
        parts = ["ERROR: No valid scores from judges"]

    for attempt in attempts:
        parts.append(f"\n--- Judge {attempt['judge_index']} ---")
        if attempt["error"]:
            parts.append(f"ERROR: {attempt['error']}")
        if attempt["response"]:
            parts.append(attempt["response"])
    return "\n".join(parts), attempts, valid_scores


def process_system(system_dir: Path, args: argparse.Namespace, api_doc: str) -> str:
    if not args.overwrite and all(path.exists() and path.stat().st_size > 0 for path in expected_score_files(system_dir, args.score_modes)):
        write_system_csv(system_dir, args.model_name, system_dir.name)
        return f"{system_dir.name}: skipped"

    dataset_system_dir = args.dataset_dir / system_dir.name
    if not dataset_system_dir.exists():
        raise FileNotFoundError(f"Dataset system not found: {dataset_system_dir}")

    client_kwargs = {}
    if args.api_key:
        client_kwargs["api_key"] = args.api_key
    if args.base_url:
        client_kwargs["base_url"] = args.base_url
    try:
        from openai import OpenAI
    except ImportError as exc:
        raise RuntimeError("The openai package is required for J-LLM scoring.") from exc

    client = OpenAI(**client_kwargs)

    for round_name, truth_name in zip(ROUND_NAMES, ("truth1.py", "truth2.py", "truth3.py")):
        prediction_path = system_dir / f"{round_name}_response.py"
        reference_path = dataset_system_dir / truth_name
        prediction = read_text(prediction_path)
        reference = read_text(reference_path)

        for mode in args.score_modes:
            path = score_path(system_dir, round_name, mode)
            if not args.overwrite and path.exists() and path.stat().st_size > 0:
                continue
            prompt = build_prompt(mode, prediction, reference, api_doc)
            response, attempts, valid_scores = run_judges(client, args, prompt)
            if not valid_scores:
                print(f"{system_dir.name} {round_name} {mode}: no valid scores")
            path.write_text(response, encoding="utf-8")

            eval_path = system_dir / f"{round_name}_evaluation_{mode}.json"
            eval_path.write_text(
                json.dumps(
                    {
                        "judge_model": args.judge_model,
                        "judge_repeats": args.judge_repeats,
                        "test_model": args.model_name,
                        "system": system_dir.name,
                        "round": round_name,
                        "mode": mode,
                        "score_file": str(path),
                        "response": response,
                        "attempts": attempts,
                        "valid_scores": valid_scores,
                        "valid_count": len(valid_scores),
                        "average_score": sum(valid_scores) / len(valid_scores) if valid_scores else None,
                        "prompt": prompt,
                    },
                    indent=2,
                    ensure_ascii=False,
                ),
                encoding="utf-8",
            )

    write_system_csv(system_dir, args.model_name, system_dir.name)
    return f"{system_dir.name}: ok"


def merge_model_csvs(model_dir: Path, combined_csv: Path) -> None:
    rows = []
    header = None
    for csv_path in sorted(model_dir.glob("*/evaluation_scores.csv")):
        with csv_path.open("r", encoding="utf-8") as csvfile:
            reader = csv.reader(csvfile)
            csv_header = next(reader)
            if header is None:
                header = csv_header
            rows.extend(reader)

    if header is None:
        raise FileNotFoundError(f"No evaluation_scores.csv files found under {model_dir}")

    combined_csv.parent.mkdir(parents=True, exist_ok=True)
    with combined_csv.open("w", newline="", encoding="utf-8") as csvfile:
        writer = csv.writer(csvfile)
        writer.writerow(header)
        writer.writerows(rows)


def main() -> None:
    args = parse_args()
    if not args.api_key and not os.environ.get("OPENAI_API_KEY"):
        raise SystemExit("OPENAI_API_KEY is required, or pass --api-key.")

    model_dir = args.output_dir / args.model_name
    if not model_dir.exists():
        raise FileNotFoundError(f"Model output directory not found: {model_dir}")

    api_doc = read_text(args.api_doc)
    system_dirs = selected_system_dirs(model_dir, args.systems)
    combined_csv = args.combined_csv or args.output_dir / f"combined_evaluation_scores_{args.judge_model}.csv"
    args.score_modes = parse_modes(args.modes)

    print(f"Model: {args.model_name}")
    print(f"Judge: {args.judge_model}")
    print(f"Systems: {len(system_dirs)}")
    print(f"Score modes: {', '.join(args.score_modes)}")
    print(f"Max workers: {args.max_workers}")

    failures = []
    with ThreadPoolExecutor(max_workers=args.max_workers) as executor:
        futures = {executor.submit(process_system, system_dir, args, api_doc): system_dir for system_dir in system_dirs}
        for future in tqdm(as_completed(futures), total=len(futures)):
            system_dir = futures[future]
            try:
                print(future.result())
            except Exception as exc:
                failures.append((system_dir.name, str(exc)))
                print(f"{system_dir.name}: fail: {exc}")

    if failures:
        print("Failures:")
        for name, message in failures:
            print(f"- {name}: {message}")
        raise SystemExit(1)

    merge_model_csvs(model_dir, combined_csv)
    print(f"Combined scores saved to {combined_csv}")


if __name__ == "__main__":
    main()
